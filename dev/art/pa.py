def hexrgb(c):
    if isinstance(c, tuple):
        return c[:3]
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))


def layout(text, font, spacing, space_w, ox=1, oy=1):
    """{(x, y): (row 1.., char index 1..)}, x just past the last glyph."""
    mask, x = {}, ox
    for i, ch in enumerate(text, 1):
        if ch == " ":
            x += space_w
            continue
        g = font[ch]
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    mask[(x + c, oy + r)] = (r + 1, i)
        x += len(g[0]) + spacing
    return mask, x - spacing


def outline(px, colour):
    solid = set(px)
    for (x, y) in list(solid):
        for dx, dy in N8:
            n = (x + dx, y + dy)
            if n not in solid:
                px[n] = colour


def to_image(px, w, h):
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for (x, y), c in px.items():
        if 0 <= x < w and 0 <= y < h:
            im.putpixel((x, y), hexrgb(c) + (255,))
    return im


def text_width(text, font=TITLE, spacing=2, space_w=4):
    return layout(text, font, spacing, space_w, 0, 0)[1]


def title_sprite(text, style, ink):
    """style: dict(bands=[10 colours], extrude=[colours]) or a function char-index -> such a dict."""
    style_of = style if callable(style) else (lambda i: style)
    mask, right = layout(text, TITLE, 2, 4, 1, 1)
    px, ext = {}, {}
    for k, (row, i) in mask.items():
        px[k] = style_of(i)["bands"][row - 1]
    for (x, y), (row, i) in mask.items():
        ex = style_of(i)["extrude"]
        for d in range(1, len(ex) + 1):
            n = (x, y + d)
            if n in mask:
                break
            if n not in ext or ext[n][0] > d:
                ext[n] = (d, ex[d - 1])
    for n, (d, c) in ext.items():
        px[n] = c
    outline(px, ink)
    return to_image(px, right + 1, 14)


def label_sprite(text, colour, ink, font=None):
    """colour: a colour or a function char-index (1-based, spaces counted) -> colour."""
    colour_of = colour if callable(colour) else (lambda i: colour)
    mask, right = layout(text, font or SMALL, 1, 3, 1, 1)
    px = {k: colour_of(i) for k, (row, i) in mask.items()}
    outline(px, ink)
    return to_image(px, right + 1, 9)


def scaled(im, s):
    return im.resize((im.width * s, im.height * s), Image.NEAREST)


def stepped_corners(w, h, cells=(4, 2, 1, 1), grid=8):
    """L mask: 255 inside, 0 in the stepped pixel corners (cells cut per row on the grid)."""
    gw, gh = w // grid, h // grid
    m = Image.new("L", (gw, gh), 255)
    for row, cut in enumerate(cells):
        for x in range(cut):
            for p in ((x, row), (gw - 1 - x, row), (x, gh - 1 - row), (gw - 1 - x, gh - 1 - row)):
                m.putpixel(p, 0)
    return m.resize((w, h), Image.NEAREST)
